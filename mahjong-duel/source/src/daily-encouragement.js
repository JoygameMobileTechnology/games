/** Stable, nonrepeating messages keyed to accumulated login days, not streaks. */
export function getDailyEncouragement(loginNumber) {
  const day = Number.isSafeInteger(loginNumber) && loginNumber > 0 ? loginNumber : 1;
  const index = day - 1;
  const opening = index % OPENINGS.length;
  const line1 = OPENINGS[opening];
  if (index < OPENINGS.length * INVITATIONS.length) {
    // The opening identifies a slot and the invitation identifies its round.
    // This visits every pairing once; the stride also varies consecutive copy.
    const invitation = (Math.floor(index / OPENINGS.length) + opening * 17) % INVITATIONS.length;
    return { line1, line2: INVITATIONS[invitation] };
  }
  // After 4,096 unique greetings (over eleven years of daily visits), keep the
  // promise of no exact repeats instead of silently cycling the original pool.
  return { line1, line2: `Make day ${day} your own.` };
}
